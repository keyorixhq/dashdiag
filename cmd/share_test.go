// share_test.go — unit tests for `dsd share`. Most tests call the package
// functions directly (isBundlePath, shareFromSnapshotFile, renderShareArtifact,
// writeShareArtifact, writeShareJSON) rather than going through cobra/rootCmd
// dispatch, mirroring cmd/root_test.go's newBareRootPreRunCmd pattern: a bare
// *cobra.Command with only the flags a given function actually reads.

