// newBareShareCmd returns a *cobra.Command carrying every flag runShare and
// its helpers read (dsd share's own local flags plus the two root persistent
// flags they also consult) — bare, so tests don't depend on rootCmd's shared
// package-level state.
func newBareShareCmd() *cobra.Command {
	c := &cobra.Command{}
	f := c.Flags()
	f.String("format", "md", "")
	f.String("from", "", "")
	f.Bool("last", false, "")
	f.Bool("stdout", false, "")
	f.Bool("no-redact", false, "")
	f.Bool("keep-hostnames", false, "")
	f.Bool("keep-ips", false, "")
	f.Bool("deep", false, "")
	f.Bool("cve", false, "")
	f.Bool("json", false, "")
	f.String("out", "", "")
	return c
}

func TestIsBundlePath(t *testing.T) {
	t.Parallel()
	cases := map[string]bool{
		"bundle.tar.gz":     true,
		"host-20260101.tgz": true,
		"snapshot.json":     false,
		"bundle.tar.gz.txt": false,
		"":                  false,
	}
	for path, want := range cases {
		if got := isBundlePath(path); got != want {
			t.Errorf("isBundlePath(%q) = %v, want %v", path, got, want)
		}
	}
}

