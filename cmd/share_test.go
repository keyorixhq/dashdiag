// dockerHostMeltdownShareSource builds a shareSource from
// fixtures/docker-host-meltdown.yaml via the same mockFixtureResults path
// `dsd mock`/`dsd demo` render through.
func dockerHostMeltdownShareSource(t *testing.T) *shareSource {
	t.Helper()
	raw, err := os.ReadFile("../fixtures/docker-host-meltdown.yaml")
	if err != nil {
		t.Fatalf("reading fixture: %v", err)
	}
	var fix MockFixture
	if err := yaml.Unmarshal(raw, &fix); err != nil {
		t.Fatalf("parsing fixture: %v", err)
	}
	results, insights := mockFixtureResults(fix)
	snap := baseline.BuildSnapshot(results, insights)
	snap.Hostname = fix.Host
	// render.BuildJSONOutput (used by writeShareJSON) reads platform.Hostname(),
	// not snap.Hostname directly — override it the same way shareFromBundle/
	// shareFromSnapshotFile do in the real flow, so a test built from a fixture
	// (rather than a live/replayed run) sees the same invariant.
	restore := platform.SetIdentity(fix.Host, fix.OS)
	t.Cleanup(restore)
	return &shareSource{
		results: results, insights: insights, snap: snap,
		elapsed: 3 * time.Second, osLabel: fix.OS,
	}
}

func TestWriteShareArtifact_SymlinkRefused(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)

	ts := time.Date(2026, 9, 23, 12, 0, 0, 0, time.UTC)
	src := &shareSource{snap: &baseline.Snapshot{Hostname: "victim-host", Timestamp: ts}}
	target := filepath.Join(dir, "victim.txt")
	if err := os.WriteFile(target, []byte("do not touch"), 0o600); err != nil {
		t.Fatal(err)
	}
	autoPath := defaultShareFilename(src.snap.Hostname, src.snap.Timestamp, "md")
	if err := os.Symlink(target, autoPath); err != nil {
		t.Fatal(err)
	}

	cmd := newBareShareCmd()
	err := writeShareArtifact(cmd, src, "report body", "md", false, share.Counts{})
	if err == nil {
		t.Fatal("expected writeShareArtifact to refuse writing through a symlink")
	}

	data, rerr := os.ReadFile(target)
	if rerr != nil {
		t.Fatal(rerr)
	}
	if string(data) != "do not touch" {
		t.Errorf("symlink target was modified: got %q", data)
	}
}

