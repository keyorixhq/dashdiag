// buildTestSnapshotFile writes a minimal baseline.Snapshot JSON file (the
// shape `dsd health --out snapshot.json` or baseline.SaveBaseline produces)
// and returns its path.
func buildTestSnapshotFile(t *testing.T, hostname string) string {
	t.Helper()
	snap := baseline.Snapshot{
		Hostname:  hostname,
		Timestamp: time.Date(2026, 9, 23, 12, 0, 0, 0, time.UTC),
		Version:   "v9.9.9",
		Checks: []baseline.CheckResult{
			{Name: "CPU Load", Status: "OK", Value: "3%"},
			{Name: "Docker", Status: "CRIT", Value: "container crash looping"},
		},
	}
	data, err := json.Marshal(snap)
	if err != nil {
		t.Fatalf("marshalling test snapshot: %v", err)
	}
	path := filepath.Join(t.TempDir(), "snapshot.json")
	if err := os.WriteFile(path, data, 0o600); err != nil {
		t.Fatalf("writing test snapshot: %v", err)
	}
	return path
}

// TestShareFromSnapshotFile is not t.Parallel(): shareFromSnapshotFile
// mutates the process-global platform identity override (platform.SetIdentity),
// which every other test in this file that touches identity also relies on —
// see dockerHostMeltdownShareSource's doc comment.
func TestShareFromSnapshotFile(t *testing.T) {
	path := buildTestSnapshotFile(t, "web-prod-01")

	src, err := shareFromSnapshotFile(path)
	if err != nil {
		t.Fatalf("shareFromSnapshotFile: %v", err)
	}
	defer src.restore()

	if src.snap.Hostname != "web-prod-01" {
		t.Errorf("snap.Hostname = %q, want web-prod-01", src.snap.Hostname)
	}
	if len(src.results) != 2 {
		t.Errorf("len(results) = %d, want 2", len(src.results))
	}
	if len(src.insights) != 1 || src.insights[0].Check != "Docker" || src.insights[0].Level != "CRIT" {
		t.Errorf("expected exactly one reconstructed CRIT insight for Docker, got %+v", src.insights)
	}
}

// TestRenderShareArtifact_AllFormats exercises every --format value against
// the docker-host-meltdown fixture (fixtures/docker-host-meltdown.yaml), via
// the same mockFixtureResults path `dsd mock`/`dsd demo` use. Not t.Parallel()
// at any level — dockerHostMeltdownShareSource mutates the process-global
// platform identity override.
func TestRenderShareArtifact_AllFormats(t *testing.T) {
	src := dockerHostMeltdownShareSource(t)

	t.Run("md", func(t *testing.T) {
		out, counts, err := renderShareArtifact("md", src, share.RedactOptions{})
		if err != nil {
			t.Fatalf("renderShareArtifact(md): %v", err)
		}
		if !strings.Contains(out, "# DashDiag Health Report") {
			t.Errorf("expected markdown report header, got:\n%s", out)
		}
		if !strings.Contains(out, "https://dashdiag.sh/checks/docker") {
			t.Errorf("expected a check-ID link to the docker catalog page, got:\n%s", out)
		}
		if !strings.Contains(out, "https://dashdiag.sh/?src=share") {
			t.Errorf("expected the footer link tagged with ?src=share, got:\n%s", out)
		}
		if strings.Contains(out, "docker-prod-01") {
			t.Errorf("expected the fixture hostname to be redacted, got:\n%s", out)
		}
		if counts.Total() == 0 {
			t.Errorf("expected nonzero redaction counts (hostname at least), got %v", counts)
		}
		if !strings.Contains(out, "**Top catch:**") {
			t.Errorf("expected a Top catch line, got:\n%s", out)
		}
	})

	t.Run("html", func(t *testing.T) {
		out, _, err := renderShareArtifact("html", src, share.RedactOptions{})
		if err != nil {
			t.Fatalf("renderShareArtifact(html): %v", err)
		}
		if !strings.Contains(out, "<!DOCTYPE html>") {
			t.Errorf("expected an HTML document, got:\n%s", out)
		}
		if !strings.Contains(out, "https://dashdiag.sh/checks/docker") {
			t.Errorf("expected a check-ID link to the docker catalog page, got:\n%s", out)
		}
		if !strings.Contains(out, `href="https://dashdiag.sh/?src=share"`) {
			t.Errorf("expected the footer link tagged with ?src=share, got:\n%s", out)
		}
		if !strings.Contains(out, "Top catch:") {
			t.Errorf("expected a Top catch line, got:\n%s", out)
		}
	})

	t.Run("text", func(t *testing.T) {
		out, _, err := renderShareArtifact("text", src, share.RedactOptions{})
		if err != nil {
			t.Fatalf("renderShareArtifact(text): %v", err)
		}
		if !strings.Contains(out, "https://dashdiag.sh/checks/docker") {
			t.Errorf("expected a check-ID link to the docker catalog page, got:\n%s", out)
		}
		if n := len(strings.Split(strings.TrimRight(out, "\n"), "\n")); n > 40 {
			t.Errorf("text format is %d lines, want <= 40:\n%s", n, out)
		}
		// Top catch must be the line immediately under Verdict.
		lines := strings.Split(out, "\n")
		verdictIdx := -1
		for i, l := range lines {
			if strings.HasPrefix(l, "Verdict:") {
				verdictIdx = i
				break
			}
		}
		if verdictIdx < 0 || verdictIdx+1 >= len(lines) || !strings.HasPrefix(lines[verdictIdx+1], "Top catch:") {
			t.Errorf("expected \"Top catch:\" on the line right after Verdict, got:\n%s", out)
		}
	})

	t.Run("blob", func(t *testing.T) {
		out, _, err := renderShareArtifact("blob", src, share.RedactOptions{})
		if err != nil {
			t.Fatalf("renderShareArtifact(blob): %v", err)
		}
		decoded, err := share.Decode(out)
		if err != nil {
			t.Fatalf("decoding blob output: %v", err)
		}
		if strings.Contains(string(decoded), "docker-prod-01") {
			t.Errorf("expected the fixture hostname to be redacted inside the blob, got:\n%s", decoded)
		}
	})

	t.Run("unknown format", func(t *testing.T) {
		if _, _, err := renderShareArtifact("pdf", src, share.RedactOptions{}); err == nil {
			t.Fatal("expected an error for an unknown format, got nil")
		}
	})
}

